--Challenge 3: International Talent Density & Cost Distribution (Aggregations)
--The Business Problem: The executive team is planning international expansion. They need a breakdown of total spending on workforce 
--costs across different regions (e.g., Canada, UK, France), showing total headcount, total payroll cost, and average performance score per country.


SELECT 
    E.COUNTRY,
    COUNT(DISTINCT E.EMP_ID) AS TOTAL_HEADCOUNT,
    -- Calculates base salary + bonus amount, substituting 0 if bonus_pct is NULL
    SUM(CH.BASE_SALARY + (CH.BASE_SALARY * (ISNULL(CH.BONUS, 0) / 100))) AS TOTAL_WORKFORCE_INVESTMENT,
    -- Averages the performance scores while rounding to 2 decimal places
    ROUND(AVG(CAST(PR.RATING AS DECIMAL(3,2))), 2) AS AVERAGE_PERFORMANCE_SCORE
FROM EMPLOYEES E
INNER JOIN (
    -- Subquery to pull only the LATEST salary record per employee
    SELECT 
        EMP_ID, 
        BASE_SALARY, 
        BONUS,
        ROW_NUMBER() OVER (PARTITION BY EMP_ID ORDER BY CHANGE_DATE DESC) as RN
    FROM COMPENSATION_HISTORY
) 
CH ON E.EMP_ID = CH.EMP_ID AND CH.RN = 1
LEFT JOIN PERFORMANCE_REVIEW PR ON E.EMP_ID = PR.EMP_ID
WHERE E.STATUS = 'Active'
GROUP BY E.COUNTRY
ORDER BY TOTAL_WORKFORCE_INVESTMENT DESC;
