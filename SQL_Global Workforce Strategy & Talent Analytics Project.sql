---CREATE COMPENSATION HISTORY TABLE ---
CREATE TABLE COMPENSATION_HISTORY
(COMP_ID INT PRIMARY KEY,
EMP_ID INT,
BASE_SALARY DECIMAL (10,2) NOT NULL,
BONUS DECIMAL(4,2)DEFAULT 0.00,
