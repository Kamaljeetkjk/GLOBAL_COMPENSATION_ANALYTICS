-- Challenge 1: Identifying Compensation Inequality ( WITH CTEs & Joins)----
--Problem: The Chief Human Resources Officer (CHRO) wants to find out which employees are earning significantly less than the average salary
-- for their specific department so they can adjust budgets and prevent people from quitting.

WITH DEPT_AVERAGE AS (
    SELECT 
        E.DEPT_ID,
        D.DEPT_NAME,
        AVG(C.BASE_SALARY) AS DEPT_AVERAGE_SALARY
    FROM EMPLOYEES E
    JOIN DEPARTMENT D ON E.DEPT_ID = D.DEPT_ID
    JOIN COMPENSATION_HISTORY C ON E.EMP_ID = C.EMP_ID
    WHERE C.CHANGE_DATE = (SELECT MAX(CHANGE_DATE) FROM COMPENSATION_HISTORY WHERE EMP_ID= E.EMP_ID) -- Latest salary
    GROUP BY E.DEPT_ID, D.DEPT_NAME)
SELECT  E.EMP_ID,E.FIRST_NAME, E.LAST_NAME, DA.DEPT_NAME, C.BASE_SALARY,DA.DEPT_AVERAGE_SALARY,
    (DA.DEPT_AVERAGE_SALARY - C.BASE_SALARY) AS SALARY_DEFICIT
FROM EMPLOYEES E
JOIN COMPENSATION_HISTORY C ON E.EMP_ID = C.EMP_ID
JOIN DEPT_AVERAGE DA ON E.DEPT_ID = DA.dept_id
WHERE C.BASE_SALARY < DA.DEPT_AVERAGE_SALARY
ORDER BY SALARY_DEFICIT DESC;

--Challenge 2: Employee Retention & Churn Risk Analysis (Window Functions)
-- The  Problem: We need to spot high-performing employees who are at risk of leaving because they haven't had a salary increase 
--or promotion in over 06 months.



WITH SALARY_HISTORY AS (
    SELECT 
        EMP_ID,
        BASE_SALARY,
        CHANGE_DATE,
        LAG(BASE_SALARY) OVER(PARTITION BY EMP_ID ORDER BY CHANGE_DATE) AS PREVIOUS_SALARY,
        ROW_NUMBER() OVER(PARTITION BY EMP_ID ORDER BY CHANGE_DATE DESC) AS RN
    FROM COMPENSATION_HISTORY
)
SELECT 
    E.EMP_ID,
    E.FIRST_NAME,
    E.LAST_NAME,
    E.COUNTRY,
    SH.BASE_SALARY AS CURRENT_SALARY,
    SH.CHANGE_DATE AS LAST_PAY_STUB_DATE,
    R.RATING AS LAST_PERFORMANCE_RATING
FROM EMPLOYEES E
JOIN SALARY_HISTORY SH ON E.EMP_ID = SH.EMP_ID
JOIN PERFORMANCE_REVIEW R ON E.EMP_ID = R.EMP_ID  
WHERE SH.RN = 1 
  AND R.RATING >= 4 
  AND SH.CHANGE_DATE < DATEADD(MONTH, -6, GETDATE())
ORDER BY R.RATING DESC;

