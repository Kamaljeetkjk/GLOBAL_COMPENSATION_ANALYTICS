FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES (EMP_ID));

---CREATE PERFORMANCE REVIEW TABLE ---
CREATE TABLE PERFORMANCE_REVIEW
(REVIEW_ID INT PRIMARY KEY,
EMP_ID INT,
REVIEW_YEAR INT NOT NULL,
RATING INT CHECK (RATING BETWEEN 1 AND 5),
FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES (EMP_ID));

